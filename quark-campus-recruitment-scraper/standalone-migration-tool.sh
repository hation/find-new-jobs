# 日志函数
log_info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# 显示横幅
show_banner() {
    echo -e "${BLUE}"
    echo "╔══════════════════════════════════════════════════════════════════╗"
    echo "║                🚀 完全独立模板迁移工具                         ║"
    echo "║               版本: v1.0.0 | 2026-05-20                         ║"
    echo "║               © 2026 夸克校园招聘爬取器项目                     ║"
    echo "╚══════════════════════════════════════════════════════════════════╝"
    echo -e "${NC}"
    echo "特点:"
    echo "  ✅ 完全独立 - 不需要其他文件"
    echo "  ✅ 随处运行 - 可以在任何目录执行"
    echo "  ✅ 包含所有模板文件"
    echo "  ✅ 自动解压和配置"
    echo ""
}

# 显示帮助
show_help() {
    echo "使用方法: $0 [选项] <项目名称>"
    echo ""
    echo "选项:"
    echo "  -h, --help     显示此帮助信息"
    echo "  -v, --verbose  显示详细输出"
    echo "  -t, --test     测试模式（不实际创建文件）"
    echo "  -c, --company  指定公司名称（默认: 新公司）"
    echo "  -u, --url      指定招聘网站URL"
    echo "  -d, --dest     指定目标目录（默认: 当前目录）"
    echo "  --clean        清理临时文件"
    echo ""
    echo "示例:"
    echo "  $0 字节跳动招聘爬取器"
    echo "  $0 -c \"阿里巴巴\" -u \"https://job.alibaba.com\" 阿里招聘爬取器"
    echo "  $0 -d ~/Desktop/projects/ 我的新项目"
    echo ""
    exit 0
}

# 清理函数
cleanup() {
    if [ -n "$TEMP_DIR" ] && [ -d "$TEMP_DIR" ]; then
        if [ "$VERBOSE" = true ]; then
            log_info "清理临时目录: $TEMP_DIR"
        fi
        rm -rf "$TEMP_DIR"
    fi
}

# 捕获退出信号
trap cleanup EXIT INT TERM

# 参数解析
VERBOSE=false
TEST_MODE=false
COMPANY_NAME="新公司"
WEBSITE_URL="https://example.com"
TARGET_DIR="."
CLEAN_MODE=false
PROJECT_NAME=""

while [[ $# -gt 0 ]]; do
    case $1 in
        -h|--help)
            show_help
            ;;
        -v|--verbose)
            VERBOSE=true
            shift
            ;;
        -t|--test)
            TEST_MODE=true
            shift
            ;;
        -c|--company)
            COMPANY_NAME="$2"
            shift 2
            ;;
        -u|--url)
            WEBSITE_URL="$2"
            shift 2
            ;;
        -d|--dest)
            TARGET_DIR="$2"
            shift 2
            ;;
        --clean)
            CLEAN_MODE=true
            shift
            ;;
        -*)
            log_error "未知选项: $1"
            show_help
            ;;
        *)
            PROJECT_NAME="$1"
            shift
            ;;
    esac
done

# 清理模式
if [ "$CLEAN_MODE" = true ]; then
    log_info "清理模式: 删除临时文件"
    rm -rf /tmp/template_migration_*
    log_success "临时文件已清理"
    exit 0
fi

# 检查项目名称
if [ -z "$PROJECT_NAME" ]; then
    log_error "请提供项目名称"
    echo ""
    show_help
fi

# 检查目标目录
if [ ! -d "$TARGET_DIR" ]; then
    log_warning "目标目录不存在: $TARGET_DIR"
    read -p "是否创建此目录？(y/N): " -n 1 -r
    echo
    if [[ $REPLY =~ ^[Yy]$ ]]; then
        mkdir -p "$TARGET_DIR"
        log_success "已创建目录: $TARGET_DIR"
    else
        log_info "操作已取消"
        exit 1
    fi
fi

