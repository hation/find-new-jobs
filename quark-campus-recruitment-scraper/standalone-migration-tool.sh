# 主函数
main() {
    show_banner
    
    log_info "独立迁移工具启动"
    log_info "项目名称: $PROJECT_NAME"
    log_info "公司名称: $COMPANY_NAME"
    log_info "网站URL: $WEBSITE_URL"
    log_info "目标目录: $TARGET_DIR"
    log_info "测试模式: $TEST_MODE"
    echo ""
    
    # 创建临时目录
    TEMP_DIR=$(mktemp -d)
    log_info "创建临时工作目录: $TEMP_DIR"
    
    # 提取模板文件
    extract_templates "$TEMP_DIR"
    
    # 执行迁移
    if [ "$TEST_MODE" = false ]; then
        # 实际执行迁移
        log_info "开始迁移到: $TARGET_DIR/$PROJECT_NAME"
        
        # 创建项目目录
        PROJECT_PATH="$TARGET_DIR/$PROJECT_NAME"
        if [ -d "$PROJECT_PATH" ]; then
            log_warning "项目目录已存在: $PROJECT_PATH"
            read -p "是否覆盖？(y/N): " -n 1 -r
            echo
            if [[ ! $REPLY =~ ^[Yy]$ ]]; then
                log_info "操作已取消"
                exit 1
            fi
            rm -rf "$PROJECT_PATH"
        fi
        
        # 复制模板文件
        mkdir -p "$PROJECT_PATH"
        cp -r "$TEMP_DIR"/. "$PROJECT_PATH"/
        
        # 重命名核心文件
        cd "$PROJECT_PATH"
        mv docs/CHECKLIST_TEMPLATE.md docs/CHECKLIST.md
        mv docs/LESSONS_LEARNED_TEMPLATE.md docs/LESSONS_LEARNED.md
        mv memory-system/CORE_BUSINESS_INFO_TEMPLATE.md CORE_BUSINESS_INFO.md
        
        # 创建目录结构
        mkdir -p output logs backup screenshots scripts tests data
        
        log_success "迁移完成！项目位置: $PROJECT_PATH"
        
        # 创建验证脚本
        cat > verify_migration.sh << 'VERIFY_EOF'
#!/bin/bash
echo "✅ 迁移验证完成"
echo "📁 项目位置: $(pwd)"
echo "📋 下一步:"
echo "  1. 配置 config/api_auth.json"
echo "  2. 阅读 docs/CHECKLIST.md"
echo "  3. 开始开发！"
VERIFY_EOF
        chmod +x verify_migration.sh
        
    else
        log_info "[测试模式] 将在以下位置创建项目:"
        log_info "  $TARGET_DIR/$PROJECT_NAME"
        log_info "包含文件:"
        find "$TEMP_DIR" -type f | head -10
    fi
    
    echo ""
    log_success "🎉 独立迁移工具执行完成！"
    echo ""
    echo "💡 使用建议:"
    echo "  1. 将此脚本复制到任何需要的地方"
    echo "  2. 运行: ./standalone-migration-tool.sh 项目名称"
    echo "  3. 无需其他文件依赖"
    echo ""
    echo "📞 支持: 如有问题，请检查日志或重新运行"
}

# 执行主函数
main "$@"